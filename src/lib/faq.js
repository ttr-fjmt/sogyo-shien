/**
 * 地域ページに載せるFAQ。
 *
 * 調査した17自治体のほぼ全てが同じ内容のQ&Aを自ら用意していた。
 * つまり実際にそこで詰まる人が多いということなので、回答エンジンに引用されやすい形
 * （Q→Aが1対1で、答えが最初の一文で完結する）で載せる。
 *
 * 自治体ごとに答えが変わる項目はデータから差し込む。
 */
import { yen } from './fmt.js';

export function faqFor(m) {
  const kabushiki = m.taxReduction.kabushiki;
  const godo = m.taxReduction.godo;
  const saved = kabushiki.before - kabushiki.after;
  const free = m.courses.filter((c) => c.fee?.free);
  const priced = m.courses.filter((c) => typeof c.fee?.amount === 'number');
  const cheapest = free.length
    ? '無料の講座があります'
    : priced.length
      ? `最も安い講座は${yen(Math.min(...priced.map((c) => c.fee.amount)))}です`
      : '受講料は公表されていません';

  const req = m.requirement.minSessions
    ? `${m.requirement.minSessions}回以上、原則${m.requirement.minMonths}か月以上にわたって支援を受け、経営・財務・人材育成・販路開拓の4分野の知識を得る必要があります。`
    : (m.requirement.lead ?? '各実施機関が定める修了条件を満たす必要があります。') +
      '詳細は実施機関にご確認ください。';

  return [
    {
      q: `${m.name}で会社を設立すると、登録免許税はいくら安くなりますか？`,
      a: `株式会社なら${yen(kabushiki.before)}が${yen(kabushiki.after)}に、合同会社なら${yen(godo.before)}が${yen(godo.after)}になります（いずれも最低税額のケース）。${m.name}の特定創業支援等事業を受け、市区町村が交付する証明書を登記申請時に法務局へ提出することが条件です。`,
    },
    {
      q: `${m.name}で証明書を受け取るには、何をすればよいですか？`,
      a: `${req}${m.name}の対象講座は${m.courses.length}件で、${cheapest}。受講後に${m.name}へ申請して証明書の交付を受けます。`,
    },
    {
      q: '会社を設立した後でも、登録免許税の軽減を受けられますか？',
      a: '受けられません。軽減を受けるには、設立登記の申請時に証明書を法務局へ提出する必要があります。登記が完了してから申請しても遡って適用されることはないため、受講と証明書の取得は登記の前に済ませてください。',
    },
    {
      q: '2社目の会社を設立する場合も対象になりますか？',
      a: '対象になりません。すでに経営している会社を続けながら新たに会社を立ち上げる場合も同様です。ただし1社目の代表を退いている、または1社目が廃業している場合は対象になることがあります。扱いは自治体により異なるため、事前にご確認ください。',
    },
    {
      q: '事業承継で代表になった場合は対象になりますか？',
      a: '対象になりません。事業承継による創業は「事業を営んでいない個人が新たに事業を開始すること」に該当しないため、証明書の交付対象外です。',
    },
    {
      q: '役員や社員が受講しても優遇措置を受けられますか？',
      a: '受けられません。法人の場合、会社法上の発起人かつ代表者となる個人本人が受講している必要があります。代表者以外が受講しても証明書は交付されません。',
    },
    {
      q: '創業してから5年以上経っていますが、対象になりますか？',
      a: '対象になりません。証明書の交付対象は、事業を営んでいない個人か、事業を開始した日から5年を経過していない個人または法人です。',
    },
    {
      q: `${m.name}の証明書を、他の市区町村で創業する場合にも使えますか？`,
      a: '優遇措置によって異なります。登録免許税の軽減は証明書を交付した市区町村内で会社を設立する場合に限られます。一方、創業関連保証の特例と小規模事業者持続化補助金〈創業型〉は、他の市区町村で創業する場合でも利用できます。日本政策金融公庫の金利引き下げは自治体により扱いが異なります。',
    },
  ];
}
