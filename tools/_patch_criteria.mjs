import fs from 'node:fs';
const dir = 'src/data/municipalities/';
const read = (s) => JSON.parse(fs.readFileSync(dir + s + '.json', 'utf8'));
const write = (s, m) => fs.writeFileSync(dir + s + '.json', JSON.stringify(m, null, 2) + '\n');

// 掲載基準を広げた。国の3措置（登録免許税・創業関連保証・公庫金利）以外の
// 上乗せ支援が公表されていれば、受講料や日程がなくても判断材料になる。
const promote = ['sendai', 'hamamatsu', 'sagamihara', 'niigata', 'naha', 'fukuoka'];
for (const s of promote) {
  const m = read(s);
  m.publish = { ready: true, blockers: [] };
  write(s, m);
  console.log('掲載に変更: ' + m.name);
}

// --- 相模原市：市の融資制度の利率引き下げを見落としていたので追加
{
  const m = read('sagamihara');
  m.otherBenefits.unshift({
    title: '相模原市創業支援融資制度の利用者負担利率の引き下げ',
    body: '利用者負担率が「0.7%以内」から「0.5%以内」に下がります。市内で1か月以内に個人事業を、または2か月以内に法人事業を開業予定の方、開業から5年未満の中小企業者が対象です。別途、金融機関や神奈川県信用保証協会の審査があります。',
  });
  m.otherBenefits = m.otherBenefits.map((b) =>
    b.title === '日本政策金融公庫'
      ? { ...b, body: '新規開業・スタートアップ支援資金の貸付利率が引き下げられます。対象は創業前の方または創業後おおむね7年以内の方です。ただし他の市区町村で創業する場合は引き下げを受けられません。' }
      : b
  );
  m.localSupport.unshift({
    title: '市の融資の利率が0.7%以内から0.5%以内に',
    body: '相模原市創業支援融資制度の**利用者負担利率が0.7%以内から0.5%以内**に下がります。借入を予定しているなら、証明書の価値は登録免許税の7万5千円分にとどまりません。',
  });
  m.highlight = {
    title: '市の融資が0.5%以内に。講座と相談の組み合わせでも条件を満たせます',
    body: '相模原市の上乗せは**創業支援融資制度の利用者負担利率が0.7%以内→0.5%以内**です。また要件の満たし方が柔軟で、相模原市産業振興財団の事業なら**創業・経営相談会と創業実践セミナーを組み合わせて1か月以上・4回以上**でかまいません。講座の日程が合わなくても相談で回数を埋められます。',
  };
  write('sagamihara', m);
  console.log('相模原市に市の融資制度を追加');
}

