// --- 福岡市：登録免許税の残り半額を市が支援する点を前面に
{
  const m = read('fukuoka');
  m.otherBenefits.unshift({
    title: '福岡市新規創業促進補助金',
    body: '登録免許税の半額軽減を活用して会社を設立する創業者に対し、市が残りの半額相当額を支援します。詳細は「福岡市新規創業促進補助金」のページをご確認ください。',
  });
  m.highlight = {
    title: '登録免許税が実質ゼロになる、全国でも珍しい自治体です',
    body: '福岡市は登録免許税の半額軽減に加えて、**市が残りの半額相当額を「福岡市新規創業促進補助金」で支援**しています。つまり株式会社なら15万円が7万5千円に下がったうえで、その7万5千円分も市の補助でまかなえます。他のどの自治体でも見つからなかった上乗せです。ただし補助金には別途の要件と審査があるため、金額と条件は必ず市のページでご確認ください。',
  };
  // 福岡市は「トップページ以外の個別ページへのリンクは各ページの担当課に問い合わせ」
  // という方針を出している。監視は個別ページで続けるが、リンクは張らない。
  m.sources = m.sources.map((s, i) =>
    i === 0
      ? {
          ...s,
          noLink: true,
          note: '福岡市は個別ページへのリンクについて担当課への問い合わせを求めているため、URLはリンクにしていません。福岡市トップページ（www.city.fukuoka.lg.jp）から「特定創業支援等事業」で検索してください。',
        }
      : s
  );
  write('fukuoka', m);
  console.log('福岡市に市の補助金を追加し、出典リンクを外しました');
}
